/** Events whose official link failed two consecutive reviewed daily checks are hidden until fixed. */
const broken = new Set(
  Object.entries((report as { listings?: Record<string, { flags: { type: string }[] }> }).listings ?? {})
    .filter(([k, v]) => k.startsWith("event:") && v.flags.some((f) => f.type === "broken_link"))
    .map(([k]) => k.slice(6)),
);

export const charityEvents: CharityEvent[] = allCharityEvents.filter((e) => e.provenance === "verified" && !broken.has(e.slug));

export function getCharityEvent(slug: string) {
  return charityEvents.find((e) => e.slug === slug);
}
